class _DataComoTexto(Dumper):
    """date e datetime vão pro banco como texto ISO, igual o sqlite3 fazia.

    As datas moram em colunas TEXT ('2024-03-31'); sem isto, uma data
    passada como date virava tipo date no servidor, e comparar texto com date
    é erro no PostgreSQL."""

    oid = 0  # tipo desconhecido: o servidor deduz pela coluna comparada

    def dump(self, obj):
        texto = obj.isoformat(sep=" ") if isinstance(obj, dt.datetime) else obj.isoformat()
        return texto.encode()


class Linha(tuple):
    """Linha de resultado que se lê por posição (linha[0]) ou por nome de
    coluna (linha["nome"]), e vira dicionário com dict(linha) — o mesmo
    contrato do sqlite3.Row, do qual o código inteiro depende."""

    _indice: dict[str, int]

    def __getitem__(self, chave):
        if isinstance(chave, str):
            return tuple.__getitem__(self, self._indice[chave])
        return tuple.__getitem__(self, chave)

    def keys(self) -> list[str]:
        return list(self._indice)


def _fabrica_de_linhas(cursor):
    if cursor.description is None:
        return tuple
    indice: dict[str, int] = {}
    for posicao, coluna in enumerate(cursor.description):
        indice.setdefault(coluna.name, posicao)

    def fazer(valores):
        linha = Linha(valores)
        linha._indice = indice
        return linha

    return fazer


# Comandos que abrem transação. Leitura roda fora dela, como no sqlite3: uma
# tela parada exibindo dados não pode deixar transação aberta no servidor,
# que seguraria travas e impediria, por exemplo, restaurar um backup.
_COMANDOS_DE_ESCRITA = ("INSERT", "UPDATE", "DELETE", "CREATE", "ALTER", "DROP", "TRUNCATE")


class Conexao:
    """A conexão com o servidor, com o mesmo jeito de usar do sqlite3:
    conn.execute(...) devolve o cursor, gravações ficam pendentes até
    conn.commit(), e leituras não prendem nada.

    Duas diferenças do PostgreSQL que ficam escondidas aqui:
    - erro dentro de uma transação a invalida inteira; a conexão desfaz a
      transação na hora, em vez de deixar todos os comandos seguintes
      falharem com "current transaction is aborted";
    - conexão que caiu (servidor reiniciado, rede fora) é refeita no próximo
      comando, em vez de o programa precisar ser fechado."""

    def __init__(self, parametros: ParametrosConexao):
        self.parametros = parametros
        self._conn = self._abrir()
        self._cache: dict | None = None

    def _abrir(self) -> psycopg.Connection:
        conn = psycopg.connect(
            **self.parametros.argumentos(), autocommit=True, row_factory=_fabrica_de_linhas
        )
        conn.adapters.register_dumper(bool, IntDumper)  # flags moram em colunas INTEGER
        conn.adapters.register_dumper(dt.date, _DataComoTexto)
        conn.adapters.register_dumper(dt.datetime, _DataComoTexto)
        conn.execute(f"SET lock_timeout = {ESPERA_DE_BLOQUEIO_MS}")
        return conn

    @property
    def em_transacao(self) -> bool:
        return self._conn.info.transaction_status != TransactionStatus.IDLE

    @contextmanager
    def leituras_repetidas_em_cache(self):
        """Dentro do bloco, a mesma consulta com os mesmos parâmetros vai ao
        servidor uma vez só. Pra relatórios que só leem e repetem muito a
        mesma pergunta (a visão geral pede a lista de sócios uma vez por
        empresa por ano). Gravar dentro do bloco esvazia o cache, pra
        ninguém ler o que já mudou."""
        self._cache = {}
        try:
            yield
        finally:
            self._cache = None

    def execute(self, sql: str, parametros=None):
        if self._cache is not None:
            comando = sql.lstrip().split(None, 1)[0].upper() if sql.strip() else ""
            if comando != "SELECT":
                self._cache.clear()
            else:
                try:
                    chave = (sql, tuple(parametros or ()))
                    hash(chave)
                except TypeError:
                    chave = None
                if chave is not None:
                    if chave not in self._cache:
                        cur = self._executar(sql, parametros)
                        self._cache[chave] = (cur.description, cur.fetchall())
                    return _ResultadoGuardado(*self._cache[chave])
        return self._executar(sql, parametros)

    def _executar(self, sql: str, parametros=None) -> psycopg.Cursor:
        if self._conn.broken:
            self._conn = self._abrir()
        comando = sql.lstrip().split(None, 1)[0].upper() if sql.strip() else ""
        try:
            if comando in _COMANDOS_DE_ESCRITA and not self.em_transacao:
                self._conn.execute("BEGIN")
            return self._conn.execute(sql, parametros)
        except psycopg.Error:
            if not self._conn.broken and self.em_transacao:
                self._conn.execute("ROLLBACK")
            raise

    def executemany(self, sql: str, lista_de_parametros) -> None:
        """Muitas gravações de uma vez, sem uma ida e volta ao servidor por
        linha — é o que faz a restauração de um backup grande terminar em
        segundos pela rede. Só serve pra gravação: abre transação."""
        if self._conn.broken:
            self._conn = self._abrir()
        try:
            if not self.em_transacao:
                self._conn.execute("BEGIN")
            with self._conn.cursor() as cur:
                cur.executemany(sql, lista_de_parametros)
        except psycopg.Error:
            if not self._conn.broken and self.em_transacao:
                self._conn.execute("ROLLBACK")
            raise

    def commit(self) -> None:
        if not self._conn.broken and self.em_transacao:
            self._conn.execute("COMMIT")

    def rollback(self) -> None:
        if not self._conn.broken and self.em_transacao:
            self._conn.execute("ROLLBACK")

    def close(self) -> None:
        self._conn.close()

    @property
    def closed(self) -> bool:
        return self._conn.closed


class _ResultadoGuardado:
    """O que o cursor devolveria, lido de novo do cache — só o que o código
    usa de um cursor: fetchone, fetchall, iteração e description."""

    def __init__(self, description, linhas):
        self.description = description
        self._linhas = iter(linhas)

    def fetchone(self):
        return next(self._linhas, None)

    def fetchall(self):
        return list(self._linhas)

    def __iter__(self):
        return self._linhas


def connect(parametros: ParametrosConexao | None = None) -> Conexao:
    parametros = parametros or conexao_configurada()
    if parametros is None:
        raise ConexaoNaoConfigurada("Este computador ainda não sabe em que servidor está o banco.")
    return Conexao(parametros)


def testar_conexao(parametros: ParametrosConexao) -> str:
    """Conecta, confere que dá pra criar as tabelas e desconecta. Devolve a
    versão do servidor; o erro, se houver, sobe pra quem chamou explicar."""
    conn = connect(parametros)
    try:
        versao = conn.execute("SHOW server_version").fetchone()[0]
        _conferir_permissao_de_criar(conn)
        return str(versao)
    finally:
        conn.close()


def _conferir_permissao_de_criar(conn: Conexao) -> None:
    """Desde o PostgreSQL 15 só o dono do banco cria tabelas no schema
    public. Sem essa checagem, um banco criado com o dono errado só daria
    erro na primeira abertura, com a mensagem crua do servidor."""
    pode = conn.execute(
        "SELECT has_schema_privilege(current_user, 'public', 'CREATE')"
    ).fetchone()[0]
    if not pode:
        raise errors.InsufficientPrivilege(
            f"O usuário {conn.parametros.usuario} não pode criar tabelas no banco "
            f"{conn.parametros.banco}."
        )


