# ------------------------------------------------ configuração local --
#
# O que é DESTE computador e não pode morar no banco: principalmente COMO
# chegar no banco. Cada PC precisa saber sozinho o endereço do servidor
# antes de conseguir abrir qualquer coisa.
ARQUIVO_CONFIG_LOCAL = "configuracao_local.json"
CHAVE_CONEXAO = "conexao"


def ler_config_local() -> dict:
    try:
        # utf-8-sig: arquivo editado no Bloco de Notas pode vir com BOM.
        return json.loads((pasta_local() / ARQUIVO_CONFIG_LOCAL).read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return {}


def gravar_config_local(chave: str, valor) -> None:
    """None apaga a chave. Relê o arquivo antes de gravar pra não perder o
    que outra parte do programa guardou nele."""
    dados = ler_config_local()
    if valor is None:
        dados.pop(chave, None)
    else:
        dados[chave] = valor
    arquivo = pasta_local() / ARQUIVO_CONFIG_LOCAL
    arquivo.parent.mkdir(parents=True, exist_ok=True)
    arquivo.write_text(json.dumps(dados, ensure_ascii=False, indent=2), encoding="utf-8")


@dataclass
class ParametrosConexao:
    """Onde está o PostgreSQL e com que usuário entrar nele.

    A senha fica em texto na configuração local: qualquer conta do Windows
    daquele PC consegue lê-la. O usuário do banco deve ser um só do sistema
    (não o postgres), dono apenas do banco do Controle de Lucros."""

    servidor: str
    porta: int = 5432
    banco: str = "controle_lucros"
    usuario: str = "controle_lucros"
    senha: str = ""

    def descricao(self) -> str:
        return f"{self.banco} em {self.servidor}:{self.porta} (usuário {self.usuario})"

    def argumentos(self) -> dict:
        return {
            "host": self.servidor,
            "port": int(self.porta),
            "dbname": self.banco,
            "user": self.usuario,
            "password": self.senha,
            "connect_timeout": ESPERA_DE_CONEXAO_S,
            "application_name": "Controle de Lucros",
            # Sem keepalive, um PC cuja rede caiu continua "conectado" pro
            # servidor por horas, segurando o que estivesse travando.
            "keepalives": 1,
            "keepalives_idle": 30,
            "keepalives_interval": 10,
            "keepalives_count": 3,
        }

    @classmethod
    def de_dicionario(cls, dados: dict) -> ParametrosConexao:
        return cls(
            servidor=str(dados.get("servidor") or ""),
            porta=int(dados.get("porta") or 5432),
            banco=str(dados.get("banco") or "controle_lucros"),
            usuario=str(dados.get("usuario") or "controle_lucros"),
            senha=str(dados.get("senha") or ""),
        )


def conexao_configurada() -> ParametrosConexao | None:
    """A conexão escolhida pra este PC, ou None se ninguém configurou ainda.

    CONTROLE_LUCROS_PG (usado pelos testes) passa na frente, no formato de
    string de conexão do libpq ("host=... port=... dbname=... user=...")."""
    override = os.environ.get("CONTROLE_LUCROS_PG")
    if override:
        partes = psycopg.conninfo.conninfo_to_dict(override)
        return ParametrosConexao(
            servidor=str(partes.get("host", "localhost")),
            porta=int(partes.get("port", 5432)),
            banco=str(partes.get("dbname", "controle_lucros")),
            usuario=str(partes.get("user", "controle_lucros")),
            senha=str(partes.get("password", "")),
        )
    dados = ler_config_local().get(CHAVE_CONEXAO)
    if not dados or not dados.get("servidor"):
        return None
    return ParametrosConexao.de_dicionario(dados)


def definir_conexao(parametros: ParametrosConexao) -> None:
    """Aponta este PC pro servidor. Só vale na próxima conexão — a já aberta
    continua onde estava."""
    gravar_config_local(CHAVE_CONEXAO, asdict(parametros))


def precisa_configurar() -> bool:
    """Instalação nova, que ainda não sabe onde fica o servidor."""
    return conexao_configurada() is None


class ConexaoNaoConfigurada(psycopg.OperationalError):
    """Nenhum servidor escolhido pra este PC."""


