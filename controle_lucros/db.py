# Rodando do código-fonte, a pasta local fica ao lado do projeto (bom pra
# desenvolvimento — dá pra achar fácil). Empacotado com o PyInstaller,
# __file__ aponta pra dentro da pasta do próprio .exe, em Arquivos de
# Programas, onde usuário comum não grava.
#
# Empacotado, ela vai pra %PROGRAMDATA% (C:\ProgramData), que é a pasta de
# dados da MÁQUINA, não a de cada conta do Windows: a conexão configurada
# uma vez vale pra quem quer que entre naquele PC. O instalador é que abre a
# permissão de escrita dessa pasta pros usuários comuns (ver [Dirs] em
# controle_lucros.iss).
NOME_DA_PASTA = "ControleDeLucros"


def _pasta_dados_padrao() -> Path:
    if getattr(sys, "frozen", False):
        base = os.getenv("PROGRAMDATA") or os.getenv("LOCALAPPDATA") or str(Path.home())
        return Path(base) / NOME_DA_PASTA / "data"
    return Path(__file__).resolve().parent.parent / "data"


def pasta_local() -> Path:
    """A pasta de dados desta máquina. Guarda a configuração da conexão, as
    preferências, os backups e o registro de falhas — coisas de um PC só.

    CONTROLE_LUCROS_DADOS (usado pelos testes) troca a pasta, pra rodar a
    suíte não gravar na configuração de quem usa o sistema."""
    override = os.environ.get("CONTROLE_LUCROS_DADOS")
    return Path(override) if override else _pasta_dados_padrao()


