def explicar_erro(erro: BaseException) -> str:
    """O texto do erro do banco trocado por algo que a pessoa entenda e saiba
    o que fazer. Com o banco no servidor, quem lê "connection refused" não
    tem como adivinhar que é o serviço do PostgreSQL que está parado."""
    if not isinstance(erro, psycopg.Error):
        return str(erro)
    if isinstance(erro, ConexaoNaoConfigurada):
        return str(erro)
    # Erro ao conectar não chega com código (sqlstate): só o texto do
    # servidor diz o que foi. E o PostgreSQL instalado num Windows em
    # português responde em português — por isso as duas línguas.
    texto = str(erro).lower() if isinstance(erro, psycopg.OperationalError) else ""
    if isinstance(erro, errors.InvalidPassword) or _contem(
        texto, "password authentication failed", "senha falhou", "role \"", "papel \""
    ):
        return (
            "O servidor recusou o usuário ou a senha do banco. Confira os dados da conexão "
            "com quem instalou o PostgreSQL."
        )
    if isinstance(erro, errors.InvalidCatalogName) or (
        _contem(texto, "database \"", "banco de dados \"") and _contem(texto, "does not exist", "não existe")
    ):
        return (
            "O servidor está no ar, mas o banco com esse nome não existe nele. Confira o nome "
            "do banco nos dados da conexão — ou peça pra criá-lo (veja o manual, "
            "\"Servidor PostgreSQL\")."
        )
    if isinstance(erro, errors.InvalidAuthorizationSpecification) or "pg_hba.conf" in texto:
        return (
            "O servidor não aceita conexões deste computador. No servidor, o arquivo "
            "pg_hba.conf precisa liberar a rede do escritório (veja o manual, \"Servidor "
            "PostgreSQL\")."
        )
    if isinstance(erro, errors.InsufficientPrivilege):
        return (
            f"{erro}\n\nO banco precisa pertencer ao usuário que o sistema usa (CREATE DATABASE "
            "... OWNER ...). Veja o manual, \"Servidor PostgreSQL\"."
        )
    if isinstance(erro, (errors.LockNotAvailable, errors.DeadlockDetected)):
        return (
            "Outro computador está gravando nesses mesmos dados agora. Espere alguns segundos "
            "e tente de novo."
        )
    if isinstance(erro, psycopg.OperationalError):
        parametros = conexao_configurada()
        onde = f"{parametros.servidor}:{parametros.porta}" if parametros else "o servidor"
        if "timeout" in texto or "timed out" in texto:
            return (
                f"O servidor do banco ({onde}) não respondeu. Confira se este computador está "
                "na rede, se o servidor está ligado e se o firewall dele libera a porta."
            )
        if "refused" in texto or "recusad" in texto:
            return (
                f"O servidor ({onde}) está na rede, mas o PostgreSQL não atendeu. Confira se o "
                "serviço do PostgreSQL está rodando nele e se a porta está certa."
            )
        if "translate host name" in texto or "resolve" in texto or "unknown host" in texto:
            return (
                f"Não encontrei o servidor \"{parametros.servidor if parametros else ''}\" na "
                "rede. Confira o nome ou use o endereço IP dele."
            )
        return (
            f"A conexão com o servidor do banco ({onde}) falhou ou caiu. O que você estava "
            "gravando pode não ter sido salvo — confira a rede e tente de novo."
        )
    return str(erro)


def _contem(texto: str, *trechos: str) -> bool:
    return any(trecho in texto for trecho in trechos)


