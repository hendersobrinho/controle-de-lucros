# Chave da trava que serializa a criação do schema: dois PCs abrindo o
# programa pela primeira vez ao mesmo tempo tentariam criar as mesmas
# tabelas, e o CREATE TABLE IF NOT EXISTS não é à prova de corrida.
_TRAVA_DO_SCHEMA = 7_216_043_901


def init_schema(conn: Conexao) -> None:
    conn.execute("BEGIN")
    try:
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (_TRAVA_DO_SCHEMA,))
        conn.execute(SCHEMA)
        conn.commit()
    except BaseException:
        conn.rollback()
        raise
